// Builds src/data/vn-map.ts: Vietnam and its neighbours as pre-projected SVG paths.
// Run after changing the extent or scale: node scripts/build-vn-map.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { feature } from 'topojson-client'

const require = createRequire(import.meta.url)
const fine = require('world-atlas/countries-10m.json')
const coarse = require('world-atlas/countries-50m.json')

// Extent covers the mainland plus Hoàng Sa and Trường Sa.
const LON0 = 101.9
const LON1 = 115.0
const LAT0 = 7.5
const LAT1 = 23.5
const K = 40 // px per degree of latitude
const KX = K * Math.cos((((LAT0 + LAT1) / 2) * Math.PI) / 180)
const W = Math.round((LON1 - LON0) * KX)
const H = Math.round((LAT1 - LAT0) * K)

const project = ([lon, lat]) => [(lon - LON0) * KX, (LAT1 - lat) * K]

// Sutherland-Hodgman against the map rectangle, in projected space.
function clip(ring) {
  const edges = [
    (p) => p[0] >= 0, (p) => p[0] <= W, (p) => p[1] >= 0, (p) => p[1] <= H,
  ]
  const cross = [
    (a, b) => [0, a[1] + ((b[1] - a[1]) * (0 - a[0])) / (b[0] - a[0])],
    (a, b) => [W, a[1] + ((b[1] - a[1]) * (W - a[0])) / (b[0] - a[0])],
    (a, b) => [a[0] + ((b[0] - a[0]) * (0 - a[1])) / (b[1] - a[1]), 0],
    (a, b) => [a[0] + ((b[0] - a[0]) * (H - a[1])) / (b[1] - a[1]), H],
  ]
  let out = ring
  for (let e = 0; e < 4 && out.length; e++) {
    const input = out
    out = []
    for (let i = 0; i < input.length; i++) {
      const cur = input[i]
      const prev = input[(i + input.length - 1) % input.length]
      const inCur = edges[e](cur)
      const inPrev = edges[e](prev)
      if (inCur) {
        if (!inPrev) out.push(cross[e](prev, cur))
        out.push(cur)
      } else if (inPrev) out.push(cross[e](prev, cur))
    }
  }
  return out
}

// Drops points closer than `tol` px to the last kept one.
function simplify(ring, tol) {
  const out = [ring[0]]
  for (const p of ring.slice(1)) {
    const q = out[out.length - 1]
    if (Math.hypot(p[0] - q[0], p[1] - q[1]) >= tol) out.push(p)
  }
  return out
}

const inArchipelagos = ([x, y]) => {
  // Hoàng Sa and Trường Sa are drawn by hand below, never as part of another country's shape.
  const [lon, lat] = [x / KX + LON0, LAT1 - y / K]
  return lon > 110.4 && lat < 17.6
}

function toPath(topology, names, tol) {
  const fc = feature(topology, topology.objects.countries)
  let d = ''
  for (const f of fc.features.filter((f) => names.includes(f.properties.name))) {
    const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates
    for (const poly of polys) {
      for (const ring of poly) {
        const pts = simplify(clip(ring.map(project)), tol)
        if (pts.length < 3) continue
        const xs = pts.map((p) => p[0])
        const ys = pts.map((p) => p[1])
        const size = Math.max(Math.max(...xs) - Math.min(...xs), Math.max(...ys) - Math.min(...ys))
        if (size < 1.2) continue
        const cx = (Math.max(...xs) + Math.min(...xs)) / 2
        const cy = (Math.max(...ys) + Math.min(...ys)) / 2
        if (names[0] !== 'Vietnam' && inArchipelagos([cx, cy])) continue
        d += 'M' + pts.map((p) => `${p[0].toFixed(1)} ${p[1].toFixed(1)}`).join('L') + 'Z'
      }
    }
  }
  return d
}

const island = (lon, lat) => project([lon, lat]).map((v) => +v.toFixed(1))
// Main features of each archipelago, approximate positions.
const hoangSa = [
  [111.61, 16.53], [111.75, 16.45], [111.5, 16.45], [112.34, 16.83], [112.73, 16.67],
  [112.21, 16.95], [111.2, 15.78], [111.79, 16.58],
].map(([a, b]) => island(a, b))
const truongSa = [
  [114.33, 11.43], [114.29, 11.06], [114.36, 10.18], [114.48, 10.38], [114.33, 9.88],
  [113.85, 10.95], [112.92, 7.89], [111.92, 8.64], [114.07, 10.72], [113.37, 8.85], [112.88, 9.33],
].map(([a, b]) => island(a, b))

const out = `// Generated by scripts/build-vn-map.mjs from world-atlas (Natural Earth). Do not edit by hand.
export const VN_MAP = {
  width: ${W},
  height: ${H},
  land: '${toPath(fine, ['Vietnam'], 0.7)}',
  neighbours: '${toPath(coarse, ['China', 'Laos', 'Cambodia', 'Thailand'], 1.2)}',
  hoangSa: ${JSON.stringify(hoangSa)} as [number, number][],
  truongSa: ${JSON.stringify(truongSa)} as [number, number][],
}

/** Longitude/latitude to map pixels, same equirectangular projection as the paths. */
export function project(lon: number, lat: number): [number, number] {
  return [(lon - ${LON0}) * ${KX.toFixed(4)}, (${LAT1} - lat) * ${K}]
}
`
writeFileSync(new URL('../src/data/vn-map.ts', import.meta.url), out)
console.log('vn-map.ts', (out.length / 1024).toFixed(1), 'KB', W, 'x', H)
